package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	cfg "github.com/jsdrews/tui-builder/internal/config"
)

const singletons = "../../internal/gen/testdata/singletons/spec.yaml"

func TestGenToStdout(t *testing.T) {
	code, stdout, stderr := run(t, "gen", singletons)
	if code != exitOK {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	if !strings.HasPrefix(stdout, "# Generated by `tui-builder gen` from "+singletons) || !strings.Contains(stdout, "#   tui-builder gen "+singletons+"\n") {
		t.Errorf("header:\n%s", stdout[:300])
	}
	if !strings.Contains(stderr, "skipped GET /legacy: deprecated") || !strings.HasSuffix(stderr, "generated 4 screens, 4 sources; skipped 4 operations\n") {
		t.Errorf("stderr:\n%s", stderr)
	}
	if _, _, stderr := run(t, "gen", "--quiet", singletons); stderr != "" {
		t.Errorf("--quiet printed %q", stderr)
	}
}

func TestGenOutputFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "status.yaml")
	if code, stdout, stderr := run(t, "gen", "-o", path, singletons); code != exitOK || stdout != "" {
		t.Fatalf("-o → %d %q %q", code, stdout, stderr)
	}
	t.Setenv("STATUS_SERVICE_API_KEY", "k")
	if _, err := cfg.Load(path); err != nil {
		t.Fatal(err)
	}
	before, _ := os.ReadFile(path)
	if code, _, stderr := run(t, "gen", "-o", path, "--name", "other", singletons); code != exitError || !strings.Contains(stderr, "already exists") {
		t.Errorf("-o over a file → %d %q", code, stderr)
	}
	if after, _ := os.ReadFile(path); string(after) != string(before) {
		t.Error("a refused -o changed the file")
	}
	if code, _, _ := run(t, "gen", "-o", path, "--force", "--name", "other", singletons); code != exitOK {
		t.Errorf("--force → %d", code)
	}
	if b, _ := os.ReadFile(path); !strings.Contains(string(b), "OTHER_API_KEY") {
		t.Error("--force didn't overwrite")
	}
}

func TestGenFailures(t *testing.T) {
	for _, tc := range []struct {
		args []string
		code int
		err  string
	}{
		{[]string{"gen"}, exitUsage, "accepts 1 arg"},
		{[]string{"gen", "a.yaml", "b.yaml"}, exitUsage, "accepts 1 arg"},
		{[]string{"gen", "--header", "nocolon", singletons}, exitUsage, "'Name: value'"},
		{[]string{"gen", "--bogus", singletons}, exitUsage, "unknown flag"},
		{[]string{"gen", "--layout", "grid", singletons}, exitUsage, "want tabs or menu"},
		{[]string{"gen", "missing.yaml"}, exitError, "no such file"},
		{[]string{"gen", "../../internal/gen/testdata/only_writes/spec.yaml"}, exitError, "nothing to generate"},
		{[]string{"gen", "../../internal/gen/testdata/relative_server/spec.yaml"}, exitError, "pass --base-url"},
	} {
		code, stdout, stderr := run(t, tc.args...)
		if code != tc.code || !strings.Contains(stderr, tc.err) || stdout != "" {
			t.Errorf("%q → %d %q, want %d with %q", tc.args, code, stderr, tc.code, tc.err)
		}
	}
}

