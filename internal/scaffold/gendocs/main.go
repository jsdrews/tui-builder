// Command gendocs turns the field tables in docs/reference into
// internal/scaffold/fields_gen.go, the field list `tui-builder init
// <kind>` writes as comments. Run it with `go generate
// ./internal/scaffold`.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// header is the header row of a field table. Tables with any other
// header (presets, locators, tokens) aren't field lists.
const header = "| Field | Type | Default | Valid on/with | What it does |"

// fieldName is a row's first cell: one YAML key in backticks.
var fieldName = regexp.MustCompile("^`([a-z0-9_]+)`$")

func main() {
	src, err := render(filepath.Join("..", "..", "docs", "reference"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("fields_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

type row struct{ name, typ, def, validOn, desc string }

type section struct {
	key  string // "components.md#table"
	rows []row
}

// render reads every page in dir and returns the generated Go source.
func render(dir string) ([]byte, error) {
	pages, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return nil, err
	}
	slices.Sort(pages)
	var all []section
	for _, p := range pages {
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		s, err := parse(filepath.Base(p), string(b))
		if err != nil {
			return nil, err
		}
		all = append(all, s...)
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by gendocs from docs/reference; DO NOT EDIT.\n\npackage scaffold\n\n")
	buf.WriteString("// reference is every field table in docs/reference, keyed by page and\n// heading anchor, in the order the page lists them.\n")
	buf.WriteString("var reference = map[string][]Field{\n")
	for _, s := range all {
		fmt.Fprintf(&buf, "%q: {\n", s.key)
		for _, r := range s.rows {
			fmt.Fprintf(&buf, "{Name: %q, Type: %q, Default: %q, ValidOn: %q, Desc: %q},\n", r.name, r.typ, r.def, r.validOn, r.desc)
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}

// parse returns a page's field tables. A heading with more than one
// table gets them all, in order.
func parse(page, text string) ([]section, error) {
	var out []section
	slugs := map[string]int{}
	var key string
	lines := strings.Split(text, "\n")
	fence := false
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		if strings.HasPrefix(line, "```") {
			fence = !fence
			continue
		}
		if fence {
			continue
		}
		if strings.HasPrefix(line, "#") {
			s := slug(strings.TrimLeft(line, "# "))
			if n := slugs[s]; n > 0 {
				slugs[s]++
				s += "-" + strconv.Itoa(n)
			} else {
				slugs[s] = 1
			}
			key = page + "#" + s
			continue
		}
		if strings.TrimSpace(line) != header {
			continue
		}
		if key == "" {
			return nil, fmt.Errorf("%s:%d: a field table before any heading", page, i+1)
		}
		i += 2 // the header and the |---| rule
		var rows []row
		for ; i < len(lines) && strings.HasPrefix(lines[i], "|"); i++ {
			cells := split(lines[i])
			if len(cells) != 5 {
				return nil, fmt.Errorf("%s:%d: %d cells, want 5", page, i+1, len(cells))
			}
			m := fieldName.FindStringSubmatch(cells[0])
			if m == nil {
				return nil, fmt.Errorf("%s:%d: the Field cell %q isn't one key in backticks", page, i+1, cells[0])
			}
			rows = append(rows, row{m[1], cells[1], cells[2], cells[3], cells[4]})
		}
		i--
		if n := len(out); n > 0 && out[n-1].key == key {
			out[n-1].rows = append(out[n-1].rows, rows...)
		} else {
			out = append(out, section{key, rows})
		}
	}
	return out, nil
}

// slug is a heading's anchor, the way the docs site and GitHub make it:
// lower case, punctuation dropped, spaces to dashes.
func slug(h string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(strings.TrimSpace(h)) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_', r == '-':
			b.WriteRune(r)
		case r == ' ':
			b.WriteByte('-')
		}
	}
	return b.String()
}

// split is a table row's cells, trimmed. A | inside backticks or
// escaped as \| stays in its cell.
func split(line string) []string {
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(strings.TrimSuffix(line, "|"), "|")
	var cells []string
	var cur strings.Builder
	code := false
	for i := 0; i < len(line); i++ {
		c := line[i]
		switch {
		case c == '\\' && i+1 < len(line) && line[i+1] == '|':
			cur.WriteByte('|')
			i++
		case c == '`':
			code = !code
			cur.WriteByte(c)
		case c == '|' && !code:
			cells = append(cells, strings.TrimSpace(cur.String()))
			cur.Reset()
		default:
			cur.WriteByte(c)
		}
	}
	return append(cells, strings.TrimSpace(cur.String()))
}
