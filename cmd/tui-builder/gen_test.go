func TestGenOverridesFlags(t *testing.T) {
	dir := t.TempDir()
	ov := filepath.Join(dir, "o.yaml")
	const things = "../../internal/fixture/things/things.yaml"
	code, stdout, stderr := run(t, "gen", "--init-overrides", ov, things)
	if code != exitOK || stdout != "" || !strings.Contains(stderr, "wrote "+ov) {
		t.Fatalf("--init-overrides → %d %q %q", code, stdout, stderr)
	}
	if code, _, stderr := run(t, "gen", "--init-overrides", ov, things); code != exitError || !strings.Contains(stderr, "already exists") {
		t.Errorf("--init-overrides over a file → %d %q", code, stderr)
	}
	if code, _, _ := run(t, "gen", "--init-overrides", ov, "-o", filepath.Join(dir, "c.yaml"), things); code != exitUsage {
		t.Errorf("--init-overrides with -o → %d, want usage", code)
	}
	os.WriteFile(ov, []byte("gen: {operations: {\"GET /things\": {title: Stock}}}\n"), 0o644)
	code, stdout, stderr = run(t, "gen", "--overrides", ov, things)
	if code != exitOK || !strings.Contains(stdout, "title: Stock") || !strings.Contains(stdout, "put changes in "+ov) {
		t.Errorf("--overrides → %d %q", code, stderr)
	}
	os.WriteFile(ov, []byte("gen: {operations: {\"GET /gone\": {title: X}}}\n"), 0o644)
	if code, _, stderr := run(t, "gen", "--overrides", ov, things); code != exitError || !strings.Contains(stderr, "--prune-overrides") {
		t.Errorf("a gone operation → %d %q", code, stderr)
	}
	if code, _, stderr := run(t, "gen", "--overrides", ov, "--prune-overrides", things); code != exitOK || !strings.Contains(stderr, "warning:") {
		t.Errorf("--prune-overrides → %d %q", code, stderr)
	}
}

// Regenerating over a config reports the spec's new operations.
func TestGenReportsNewOperations(t *testing.T) {
	dir := t.TempDir()
	spec := filepath.Join(dir, "spec.yaml")
	b, _ := os.ReadFile(singletons)
	os.WriteFile(spec, b, 0o644)
	out := filepath.Join(dir, "c.yaml")
	if code, _, stderr := run(t, "gen", "-o", out, spec); code != exitOK {
		t.Fatalf("first run: %s", stderr)
	}
	more := strings.Replace(string(b), "paths:\n", "paths:\n  /status:\n    get:\n      responses: {\"200\": {description: OK, content: {application/json: {schema: {type: object, properties: {up: {type: boolean}}}}}}}\n", 1)
	os.WriteFile(spec, []byte(more), 0o644)
	code, _, stderr := run(t, "gen", "-o", out, "--force", spec)
	if code != exitOK || !strings.Contains(stderr, "new in the spec: GET /status") || strings.Contains(stderr, "gone from the spec") {
		t.Errorf("regenerate → %d %q", code, stderr)
	}
}
